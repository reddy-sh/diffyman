"""Generate ``python/diffyman/types.py`` from the Diff Document JSON Schema.

The typed views of the document are never written by hand
(docs/adr/0007-binding-strategy.md): this script turns the JSON Schema that
``diffyman schema`` prints into ``TypedDict`` classes and ``Literal`` aliases.
It uses only the standard library.

    python tools/gen_types.py            # write python/diffyman/types.py
    python tools/gen_types.py --check    # exit 1 if the file is out of date
    diffyman schema | python tools/gen_types.py --schema -

Without ``--schema`` the schema comes from the installed extension
(``diffyman._native.document_schema()``), which prints the same text as
``diffyman schema``. The mapping is deliberately small and fails loudly on a
schema construct it does not know, so a schema change cannot be dropped
silently:

- an object definition becomes a ``TypedDict`` (optional properties become
  ``NotRequired``; ``additionalProperties: true`` is noted in the docstring);
- a ``oneOf`` of string constants becomes a ``Literal`` alias;
- ``anyOf`` with ``{"type": "null"}`` becomes ``X | None``;
- ``integer`` is ``int``, ``number`` is ``float``, an empty schema is ``Any``.
"""

from __future__ import annotations

import argparse
import builtins
import json
import keyword
import pathlib
import re
import sys
import textwrap
from collections.abc import Mapping, Sequence
from typing import Any

HERE = pathlib.Path(__file__).resolve().parent
OUTPUT = HERE.parent / "python" / "diffyman" / "types.py"
WIDTH = 99
ROOT_NAME = "DiffDocument"

Schema = Mapping[str, Any]

HEADER = '''\
"""Typed views of the Diff Document (docs/spec/diff-document.md).

Generated by ``bindings/python/tools/gen_types.py`` from the JSON Schema that
``diffyman schema`` prints. Do not edit by hand: run the script again after a
schema change (a test checks that this file is current).

The classes are ``TypedDict`` definitions, so a document stays a plain
``dict`` (what :func:`json.loads` returns) and the types only guide a type
checker. Every key the schema requires is required here.
"""

from __future__ import annotations

'''

# Keywords that document a value but do not change its Python type.
ANNOTATION_ONLY = frozenset(
    {"description", "default", "title", "examples", "format", "minimum", "maximum"}
)

PRIMITIVES = {
    "string": "str",
    "integer": "int",
    "number": "float",
    "boolean": "bool",
    "null": "None",
}


class SchemaError(ValueError):
    """The schema uses a construct this generator does not map."""


def class_name(name: str) -> str:
    """The Python name of a schema definition (builtins get a ``Diff`` prefix)."""
    if not name.isidentifier() or keyword.iskeyword(name):
        raise SchemaError(f"definition name {name!r} is not a Python identifier")
    return f"Diff{name}" if hasattr(builtins, name) else name


def ref_name(ref: str) -> str:
    prefix = "#/$defs/"
    if not ref.startswith(prefix):
        raise SchemaError(f"unsupported $ref {ref!r}")
    return class_name(ref[len(prefix) :])


def literal(values: Sequence[str]) -> str:
    return "Literal[" + ", ".join(json.dumps(v) for v in values) + "]"


def string_consts(variants: Sequence[Schema]) -> list[str] | None:
    """The values of a ``oneOf`` made of string constants, or ``None``."""
    values: list[str] = []
    for v in variants:
        if set(v) - {"const", "type", "description"} or not isinstance(v.get("const"), str):
            return None
        if v.get("type", "string") != "string":
            return None
        values.append(v["const"])
    return values


def py_type(node: Schema | bool, where: str) -> str:
    """The annotation for a schema node (a property, an item or a definition)."""
    if node is True:
        return "Any"
    if not isinstance(node, Mapping):
        raise SchemaError(f"{where}: unsupported schema {node!r}")
    keys = set(node) - ANNOTATION_ONLY
    if not keys:
        return "Any"
    if "$ref" in node:
        if keys != {"$ref"}:
            raise SchemaError(f"{where}: $ref with siblings {sorted(keys)}")
        return ref_name(node["$ref"])
    if "anyOf" in node or "oneOf" in node:
        variants = node.get("anyOf", node.get("oneOf"))
        if keys != {"anyOf"} and keys != {"oneOf"}:
            raise SchemaError(f"{where}: unsupported combination {sorted(keys)}")
        consts = string_consts(variants)
        if consts is not None:
            return literal(consts)
        parts = [py_type(v, f"{where}/{i}") for i, v in enumerate(variants)]
        return " | ".join(dict.fromkeys(parts))
    if "const" in node:
        return literal([node["const"]])
    if "enum" in node:
        if not all(isinstance(v, str) for v in node["enum"]):
            raise SchemaError(f"{where}: enum of non-strings")
        return literal(node["enum"])
    kind = node.get("type")
    if isinstance(kind, list):
        if keys != {"type"}:
            raise SchemaError(f"{where}: type list with siblings {sorted(keys)}")
        return " | ".join(PRIMITIVES[k] for k in kind)
    if kind in PRIMITIVES:
        if keys != {"type"}:
            raise SchemaError(f"{where}: {kind} with {sorted(keys)}")
        return PRIMITIVES[kind]
    if kind == "array":
        if keys - {"type", "items"}:
            raise SchemaError(f"{where}: array with {sorted(keys)}")
        return f"list[{py_type(node.get('items', True), where + '/items')}]"
    if kind == "object":
        open_map = node.get("additionalProperties", True) is True
        if keys - {"type", "additionalProperties"} or not open_map:
            raise SchemaError(f"{where}: inline object {sorted(keys)} needs a $defs entry")
        return "dict[str, Any]"
    raise SchemaError(f"{where}: unsupported schema {dict(node)!r}")


def paragraphs(text: str) -> list[str]:
    """Doc-comment text as paragraphs with their line breaks joined."""
    return [" ".join(p.split()) for p in re.split(r"\n\s*\n", text.strip()) if p.strip()]


def docstring(text: str, indent: str) -> list[str]:
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    paras = paragraphs(text)
    if not paras:
        return []
    one = f'{indent}"""{paras[0]}"""'
    if len(paras) == 1 and len(one) <= WIDTH:
        return [one]
    lines: list[str] = []
    for i, p in enumerate(paras):
        if i:
            lines.append("")
        first = f'{indent}"""' if i == 0 else indent
        lines += textwrap.wrap(p, WIDTH, initial_indent=first, subsequent_indent=indent,
                               break_on_hyphens=False)
    lines.append(f'{indent}"""')
    return lines


def comment(text: str, indent: str) -> list[str]:
    lines: list[str] = []
    for i, p in enumerate(paragraphs(text)):
        if i:
            lines.append(f"{indent}#:")
        lines += textwrap.wrap(p, WIDTH - len(indent) - 3, initial_indent=f"{indent}#: ",
                               subsequent_indent=f"{indent}#: ", break_on_hyphens=False)
    return lines


def wrap_assignment(target: str, value: str) -> list[str]:
    """``target = value``, split inside the outermost brackets when too long."""
    line = f"{target} = {value}"
    if len(line) <= WIDTH:
        return [line]
    head, _, rest = value.partition("[")
    items = [i.strip() for i in rest.removesuffix("]").split(", ")]
    return [f"{target} = {head}[", *(f"    {i}," for i in items), "]"]


def field_order(node: Schema) -> list[str]:
    props = node.get("properties", {})
    required = [p for p in node.get("required", []) if p in props]
    return required + sorted(p for p in props if p not in required)


def render_typed_dict(name: str, node: Schema, where: str) -> list[str]:
    props: Mapping[str, Any] = node.get("properties", {})
    required = set(node.get("required", []))
    extra = node.get("additionalProperties", False)
    if extra not in (True, False):
        raise SchemaError(f"{where}: additionalProperties must be true or false")
    # A key such as `from` cannot be a class attribute. The functional form
    # evaluates its values, so each annotation is a string there (outside
    # `NotRequired`, which must stay visible at run time).
    functional = any(not p.isidentifier() or keyword.iskeyword(p) for p in props)
    fields: list[tuple[str, str, str]] = []
    for prop in field_order(node):
        annotation = py_type(props[prop], f"{where}/properties/{prop}")
        if functional:
            annotation = json.dumps(annotation)
        if prop not in required:
            annotation = f"NotRequired[{annotation}]"
        fields.append((prop, annotation, props[prop].get("description", "")))
    description = node.get("description", "")
    if extra:
        description += "\n\nOther keys may be present (``additionalProperties``)."
    if functional:
        out = [f"{name} = TypedDict(", f"    {json.dumps(name)},", "    {"]
        for prop, annotation, text in fields:
            out += comment(text, "        ")
            out.append(f"        {json.dumps(prop)}: {annotation},")
        out += ["    },", ")"]
        # A string right after the assignment is its attribute docstring.
        out += docstring(description, "")
        return out
    out = [f"class {name}(TypedDict):"]
    out += docstring(description, "    ")
    if fields:
        out.append("")
    for prop, annotation, text in fields:
        out += comment(text, "    ")
        out.append(f"    {prop}: {annotation}")
    if not fields and not description:
        out.append("    pass")
    return out


def render(schema: Schema) -> str:
    """The text of ``types.py`` for a Diff Document schema."""
    if schema.get("title") != ROOT_NAME:
        raise SchemaError(f"the root title must be {ROOT_NAME!r}, not {schema.get('title')!r}")
    defs: Mapping[str, Schema] = schema.get("$defs", {})
    aliases: list[list[str]] = []
    classes: list[list[str]] = []
    names = [class_name(n) for n in defs] + [ROOT_NAME]
    if len(set(names)) != len(names):
        raise SchemaError("two definitions map to the same Python name")
    for raw, node in sorted(defs.items(), key=lambda item: class_name(item[0])):
        name = class_name(raw)
        where = f"#/$defs/{raw}"
        if node.get("type") == "object" and "properties" in node:
            classes.append(render_typed_dict(name, node, where))
        else:
            block = comment(node.get("description", ""), "")
            block += wrap_assignment(f"{name}: TypeAlias", py_type(node, where))
            aliases.append(block)
    root = dict(schema)
    root.pop("$defs", None)
    classes.append(render_typed_dict(ROOT_NAME, root, "#"))

    body = "\n\n".join("\n".join(b) for b in aliases)
    body += "\n\n\n" + "\n\n\n".join("\n".join(c) for c in classes)
    imports = ["Any", "Literal", "TypeAlias", "TypedDict"]
    if "NotRequired[" in body:
        imports.append("NotRequired")
    used = [i for i in sorted(imports) if re.search(rf"\b{i}\b", body)]
    exports = sorted(names)
    out = HEADER + f"from typing import {', '.join(used)}\n\n"
    out += "__all__ = [\n" + "".join(f'    "{n}",\n' for n in exports) + "]\n\n\n"
    out += body + "\n"
    return out


def load_schema(source: str | None) -> Schema:
    if source is None:
        from diffyman import _native

        text = _native.document_schema()
    elif source == "-":
        text = sys.stdin.read()
    else:
        text = pathlib.Path(source).read_text(encoding="utf-8")
    loaded = json.loads(text)
    if not isinstance(loaded, dict):
        raise SchemaError("the schema must be a JSON object")
    return loaded


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--schema", help="schema file (`diffyman schema` output), or - for stdin")
    parser.add_argument("--output", default=str(OUTPUT), help="where to write types.py")
    parser.add_argument("--check", action="store_true", help="exit 1 if the output is stale")
    args = parser.parse_args(argv)
    text = render(load_schema(args.schema))
    output = pathlib.Path(args.output)
    if args.check:
        current = output.read_text(encoding="utf-8") if output.exists() else ""
        if current != text:
            print(f"{output.name} is out of date: run tools/gen_types.py", file=sys.stderr)
            return 1
        return 0
    output.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
